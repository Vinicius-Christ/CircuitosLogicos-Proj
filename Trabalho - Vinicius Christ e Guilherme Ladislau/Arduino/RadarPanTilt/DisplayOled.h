static byte oledN;

static inline void oledCmd(byte c) {
  Wire.beginTransmission(OLED_ENDERECO);
  Wire.write((byte)0x00);
  Wire.write(c);
  Wire.endTransmission();
}

static inline void oledInicia() {
  for (byte i = 0; i < sizeof(OLED_INIT); i++) oledCmd(pgm_read_byte(&OLED_INIT[i]));
}

static inline void oledPos(byte col, byte pagina) {
  oledCmd(0x21); oledCmd(col); oledCmd(127);
  oledCmd(0x22); oledCmd(pagina); oledCmd(pagina);
}

static inline void oledAbre() {
  Wire.beginTransmission(OLED_ENDERECO);
  Wire.write((byte)0x40);
  oledN = 0;
}

static inline void oledByte(byte b) {
  if (oledN >= 30) {
    Wire.endTransmission();
    oledAbre();
  }
  Wire.write(b);
  oledN++;
}

static inline void oledFim() { Wire.endTransmission(); }

static inline void oledIni(byte col, byte pagina) {
  oledPos(col, pagina);
  oledAbre();
}

static inline void oledChar(char c) {
  if (c < 32 || c > 126) c = 32;
  const byte *p = &OLED_FONTE[(c - 32) * 5];
  for (byte i = 0; i < 5; i++) oledByte(pgm_read_byte(p + i));
  oledByte(0);
}

static inline byte oledEscP(const __FlashStringHelper* s) {
  PGM_P p = (PGM_P)s;
  byte n = 0;
  char c;
  while ((c = pgm_read_byte(p++))) { oledChar(c); n++; }
  return n;
}

static inline byte oledEsc(const char* s) {
  byte n = 0;
  while (*s) { oledChar(*s++); n++; }
  return n;
}

static inline byte oledEscNum(int v, byte largura) {
  char b[7];
  byte n = 0;
  unsigned int u = (v < 0) ? -v : v;
  do { b[n++] = '0' + u % 10; u /= 10; } while (u);
  if (v < 0) b[n++] = '-';
  byte total = n;
  for (byte i = n; i < largura; i++) { oledChar(' '); total++; }
  while (n) oledChar(b[--n]);
  return total;
}

static inline void oledLimpa() {
  for (byte pagina = 0; pagina < 8; pagina++) {
    oledIni(0, pagina);
    for (byte i = 0; i < 128; i++) oledByte(0);
    oledFim();
  }
}

